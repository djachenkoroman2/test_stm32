#pragma once

// =============================================================================
// debug_log.h - неблокирующий отладочный вывод в Serial (USB CDC)
// =============================================================================
//
// Строка выводится, только если порт открыт и в буфере USB есть место под
// неё целиком. Иначе она отбрасывается: контур регулирования никогда не
// ждёт USB.

#include <stdint.h>

void debugLog(const char *format, ...) __attribute__((format(printf, 1, 2)));

// Сколько строк отброшено с запуска.
uint32_t debugDroppedLines();
