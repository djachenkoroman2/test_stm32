#pragma once

// =============================================================================
// quadrature_encoder.h - квадратурный энкодер: таймер или внешние прерывания
// =============================================================================
//
// Оба вида считают x4 (оба фронта обеих фаз) с одинаковым знаком: счёт
// растёт, когда фаза A опережает B.
//
// - EncoderKind::Timer: режим энкодера таймера (SMS = 011). Считает
//   аппаратно, без нагрузки на процессор. 16-битный счётчик расширяется до
//   32 бит в update(): за период контура (10 мс) набегает не больше сотни
//   отсчётов, до переполнения int16 далеко.
// - EncoderKind::Exti: прерывание на каждый фронт A и B, декодирование по
//   таблице переходов. Двойной скачок (оба сигнала сменились между
//   прерываниями) не считается и увеличивает счётчик ошибок — признак помех
//   или слишком высокой частоты.
//
// Порядок использования: begin() один раз, update() раз в период контура,
// count() — когда угодно после update().

#include <Arduino.h>
#include "config.h"

class QuadratureEncoder
{
public:
  // slot — номер мотора 0..MOTOR_COUNT-1, нужен для обработчика прерывания.
  void begin(const MotorPins &pins, uint8_t slot);

  // Переносит аппаратный счётчик в 32-битный накопитель.
  void update();

  // Накопленный счёт, отсчёты x4.
  int32_t count() const;

  // Устанавливает накопленный счёт (например, сброс в 0).
  void setCount(int32_t value);

  // Число отброшенных двойных переходов с момента запуска (только EXTI).
  uint32_t glitches() const;

private:
  EncoderKind kind_ = EncoderKind::Timer;
  TIM_TypeDef *timer_ = nullptr;
  uint8_t slot_ = 0;
  uint16_t lastTimerCount_ = 0;
  int32_t total_ = 0; // только для EncoderKind::Timer
};
