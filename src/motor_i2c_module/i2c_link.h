#pragma once

// =============================================================================
// i2c_link.h - I2C slave: транспорт между прерыванием и loop()
// =============================================================================
//
// Обработчики Wire (onReceive / onRequest) выполняются в прерывании I2C.
// Здесь они только копируют байты:
//   - запись [регистр] (1 байт) задаёт указатель чтения — прямо в
//     прерывании, потому что onRequest при повторном старте приходит сразу за
//     ней и должен отдать данные немедленно;
//   - запись [регистр, данные..., CRC] кладётся в очередь, разбирает её
//     loop() через popFrame();
//   - чтение отдаёт байты из снимка карты регистров, который loop()
//     обновляет через publish().
// Любая транзакция по адресу модуля обновляет время последнего обращения
// (watchdog связи).

#include <stdint.h>
#include "register_map.h"

namespace i2c_link
{
// Наибольшая транзакция Wire (буфер ядра): 1 байт адреса регистра + до 30
// байтов данных + CRC.
constexpr uint8_t MAX_FRAME = 32;

struct Frame
{
  uint8_t length;
  uint8_t bytes[MAX_FRAME];
};

void begin();

// Следующая принятая запись. false — очередь пуста.
bool popFrame(Frame &frame);

// Атомарно заменяет снимок карты регистров, из которого отвечает onRequest.
void publish(const uint8_t (&image)[reg::MAP_SIZE]);

// millis() последней транзакции по адресу модуля.
uint32_t lastContactMs();

// Сколько записей потеряно из-за переполнения очереди с прошлого вызова.
uint16_t takeDroppedFrames();
} // namespace i2c_link
